package dev.nandi0813.api.Enum;

/**
 * Places where ZonePractice Pro renders a player name.
 */
public enum NameLocation {
    /** Above-head nametag (scoreboard team prefix/suffix). */
    NAMETAG,
    /** Tab list name. */
    TAB,
    /** Chat format name. */
    CHAT,
    /** Full-name sidebar placeholders such as %player% (not the NameOnly variants). */
    SIDEBAR
}
